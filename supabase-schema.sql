-- Jalankan di Supabase SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'viewer' check (role in ('admin','viewer'))
);
create table if not exists public.collections (
  id bigint generated by default as identity primary key,
  title text not null,
  artist text default '',
  category text not null check (category in ('Vinyl','Kaset Pita','VCD Lagu','VCD Film')),
  genre text default '', year text default '', label text default '',
  condition text default 'Belum diperiksa', description text default '',
  images jsonb not null default '[]'::jsonb,
  featured boolean not null default false,
  created_at timestamptz not null default now()
);
create or replace function public.is_archive_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin'); $$;
alter table public.profiles enable row level security;
alter table public.collections enable row level security;
create policy "profiles read own" on public.profiles for select to authenticated using (id = auth.uid());
create policy "public read collections" on public.collections for select to anon, authenticated using (true);
create policy "admins insert collections" on public.collections for insert to authenticated with check (public.is_archive_admin());
create policy "admins update collections" on public.collections for update to authenticated using (public.is_archive_admin()) with check (public.is_archive_admin());
create policy "admins delete collections" on public.collections for delete to authenticated using (public.is_archive_admin());
insert into storage.buckets (id,name,public) values ('collection-images','collection-images',true) on conflict (id) do nothing;
create policy "public view collection images" on storage.objects for select to anon, authenticated using (bucket_id = 'collection-images');
create policy "admins upload collection images" on storage.objects for insert to authenticated with check (bucket_id = 'collection-images' and public.is_archive_admin());
create policy "admins update collection images" on storage.objects for update to authenticated using (bucket_id = 'collection-images' and public.is_archive_admin());
create policy "admins delete collection images" on storage.objects for delete to authenticated using (bucket_id = 'collection-images' and public.is_archive_admin());
